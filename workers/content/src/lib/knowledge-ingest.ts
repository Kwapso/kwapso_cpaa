/** EVERY WAY A COLLEAGUE'S NAME GETS TYPED, beside the one it is stored as.
 *
 * The owner asked for "Alex's full name" and got nothing, and the reason is
 * mechanical rather than clever: the lexical arm of the search matches LETTERS,
 * so a question containing "Alex" reaches a passage containing "Alexander" only
 * if the shorter form is written somewhere in it. Nobody ever writes it down —
 * a person's row holds the name on their passport, and the office calls them
 * something else.
 *
 * DERIVED, NOT A NICKNAME TABLE, which would be a second source of truth about
 * people and wrong within a month. Three shapes, and all three are the same
 * string a person already has: the first name alone, the local part of their
 * own email address (which is what they chose to be called by a machine), and
 * the short form the email gives when it differs from the first name — Alexander
 * Stadlmair at alex@ yields "Alex". The stored full name is NOT repeated here;
 * the sentence above this one already carries it.
 *
 * A shortening that is not in the email and is not the first name is not
 * guessable and is deliberately not guessed: a wrong alias would put one
 * colleague's passage in front of a question about another, which is worse than
 * the miss it would have fixed. */
export function nameSpellings(
  firstName: string | null,
  lastName: string | null,
  email: string
): string[] {
  const first = (firstName ?? "").trim()
  const last = (lastName ?? "").trim()
  const local = email.split("@")[0] ?? ""
  const out: string[] = []
  const add = (value: string) => {
    const clean = value.trim()
    if (!clean || clean.length < 2) return
    if (out.some((v) => v.toLowerCase() === clean.toLowerCase())) return
    out.push(clean)
  }
  if (first) add(first)
  // The email's local part, as a NAME rather than as an address: `alex.stadlmair`
  // and `alex_s` are how somebody is addressed by a machine and are also how a
  // colleague types their name into a search box in a hurry.
  for (const piece of local.split(/[._-]+/)) add(piece.charAt(0).toUpperCase() + piece.slice(1))
  if (first && last) add(`${first.charAt(0)}. ${last}`)
  return out
}

/** The first sentence of a ticket's description, for a ticket that has no title
 * of its own. Bounded so a wall of pasted text can't become a title.
 *
 * A SENTENCE ENDS WITH PUNCTUATION AND THEN A GAP. It used to end at the first
 * full stop of any kind, which turned "Bergman S.A. cannot see the March invoice
 * run" into a ticket called "Bergman S" — and the title is not a detail here, it
 * is the words a citation puts in front of a reader when the assistant answers.
 * An abbreviation's dots are followed by a letter, so requiring whitespace (or
 * the end of the text) tells the two apart without a list of abbreviations. */
function firstLine(description: string): string {
  const text = plainText(description)
  const stop = text.search(/[.!?](\s|$)|\n/)
  const line = (stop > 0 ? text.slice(0, stop + 1) : text).trim()
  return (line || "Untitled ticket").slice(0, 120)
}

/** What one kind's tick did. Returned to the door AND recorded on the row, so a
 * person watching the screen and a person reading the table see one story. */
export type SweepResult = {
  kind: string
  read: number
  indexed: number
  /** true when this kind has caught up with its table (nothing left past cursor) */
  caughtUp: boolean
  error?: string
}

/** THE STORED POSITION, WITH THE TEXT BUILDER THAT WROTE IT.
 *
 * `v<version>|<sort value>|<row id>`. A cursor whose version is not the kind's
 * current one is not a position — it is a page number in a book that has been
 * rewritten — so it reads as null and the kind starts its table again. A cursor
 * written before versions existed has no `v` prefix and is read the same way,
 * which is exactly right: those rows were written by an older builder too. */
function parseCursor(raw: string | null, version: number): Cursor | null {
  if (!raw) return null
  const stamped = /^v(\d+)\|/.exec(raw)
  if (!stamped || Number(stamped[1]) !== version) return null
  const rest = raw.slice(stamped[0].length)
  const cut = rest.indexOf("|")
  return cut === -1 ? null : { at: rest.slice(0, cut), id: rest.slice(cut + 1) }
}

const writeCursor = (cursor: Cursor, version: number): string => `v${version}|${cursor.at}|${cursor.id}`

/** File one slice of one kind. Every row becomes (or updates) exactly one
 * source, and only a row whose TEXT changed is re-chunked and re-embedded.
 *
 * A source somebody EXCLUDED stays excluded: the upsert leaves `deactivated_at`
 * alone and `indexSource` refuses to index a deactivated row, so a sweep can
 * never quietly hand back material a person deliberately took away. */
async function sweepKind(
  env: Env,
  cfg: D1Rest,
  guard: MemberGuard,
  kind: IngestKind,
  limit = INGEST_SOURCES_PER_TICK
): Promise<SweepResult> {
  const stateKey = kind.stateKey ?? kind.kind
  const state = await d1Query<{ cursor: string | null }>(
    cfg,
    guard.databaseId,
    // R14: one row by primary key.
    "SELECT cursor FROM knowledge_ingest WHERE kind = ? LIMIT 1",
    [stateKey]
  )
  const cursor = parseCursor(state[0]?.cursor ?? null, kind.textVersion)
  let rows = await kind.read(cfg, guard, cursor, limit, env)
  let indexed = 0
  let last: Cursor | null = cursor

  // A WINDOWED KIND THAT HAS CAUGHT UP REWINDS, AND RE-WALKS IN THE SAME TICK.
  //
  // It read nothing past its cursor, which for a sliding window means "nothing
  // NEWER" rather than "nothing left" — so the position is dropped and the
  // window is walked again from the start, now.
  //
  // Doing it in the same tick rather than leaving it for the next one is the
  // difference between a shelf move landing on the next press and landing on the
  // one after: a person who moves a folder to the team's shelf and asks kwapso to
  // bring it in has changed nothing about the FILE, so there is nothing newer for
  // a cursor to find, and a tick that only rewound would file nothing at all.
  //
  // Cheap by construction: everything it re-meets is hash-skipped (no chunking,
  // no embedding, one upsert), and it costs at most ONE extra listing per kind
  // per tick. Bounded, once — not a loop.
  if (kind.windowed && rows.length === 0 && cursor) {
    last = null
    rows = await kind.read(cfg, guard, null, limit, env)
  }

  for (const row of rows) {
    const compartment = row.accountId ? accountCompartment(row.accountId) : AGENCY_COMPARTMENT
    const hash = contentHash(indexableText({ title: row.title, body: row.body }))
    const now = new Date().toISOString()
    // ONE STATEMENT decides create-or-update, so two ticks running at once (a
    // cron and a catch-up call) cannot both insert the same source. The conflict
    // target names the partial index's own WHERE clause, which is what makes it
    // match. `deactivated_at` is deliberately absent from the SET list.
    const upserted = await d1Query<{
      id: string
      content_hash: string | null
      deactivated_at: string | null
      /** NULL when the APP retired this source and not a person — see the
       * revival below. `setSourceActive` stamps the actor's id; the two retire
       * paths here stamp only the brand's name. */
      deactivator_id: string | null
      chunk_count: number
      indexed_chunks: number
    }>(
      cfg,
      guard.databaseId,
      `INSERT INTO knowledge_sources
         (id, kind, origin_table, origin_row_id, compartment, account_id, owner_user_id,
          app_id, ticket_id, sprint_id, record_date, title, summary, body, body_bytes,
          source_url, created_at, creator_name)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ${sqlString(brand.name)})
       ON CONFLICT (origin_table, origin_row_id) WHERE origin_row_id IS NOT NULL
       DO UPDATE SET title = excluded.title, summary = excluded.summary, body = excluded.body,
                     body_bytes = excluded.body_bytes, source_url = excluded.source_url,
                     compartment = excluded.compartment, account_id = excluded.account_id,
                     app_id = excluded.app_id, ticket_id = excluded.ticket_id, sprint_id = excluded.sprint_id,
                     record_date = excluded.record_date,
                     owner_user_id = excluded.owner_user_id,
                     content_hash = CASE WHEN knowledge_sources.owner_user_id IS excluded.owner_user_id
                                         THEN knowledge_sources.content_hash ELSE NULL END,
                     updated_at = ?
       RETURNING id, content_hash, deactivated_at, deactivator_id, chunk_count, indexed_chunks`,
      [
        ulid(),
        kind.kind,
        kind.table,
        row.originRowId,
        compartment,
        row.accountId,
        // THE PERSONAL FENCE TRAVELS ON THE UPSERT, and it is in the SET list on
        // purpose: somebody who moves a folder from their own shelf to the
        // team's has changed who this material may answer for, and a source that
        // kept the old owner would go on being invisible to the colleague it was
        // just shared with. It travels the other way too — team back to private
        // — which is the direction that matters, and the hash is cleared with it
        // so the chunks are rebuilt under the new fence.
        row.ownerUserId,
        row.appId ?? null,
        row.ticketId ?? null,
        row.sprintId ?? null,
        row.recordDate ?? null,
        row.title,
        // A kind with no summary of its own (Google's four) falls back to its
        // title — the router still has a sentence to route on, and the column
        // never holds undefined.
        row.summary ?? row.title,
        row.body,
        new TextEncoder().encode(row.body).length,
        row.sourceUrl,
        now,
        now,
      ]
    )
    const source = upserted[0]
    last = { at: row.sortAt, id: row.originRowId }
    if (!source) continue
    // THE ROW HAS LEFT THE APP — archived, switched off. Its source stops being
    // readable, which is exactly what a person taking one away does. Recorded on
    // the source rather than skipped in the read, because a skipped row is a row
    // the cursor never visits again: that is how an archived ticket would go on
    // answering questions forever.
    if (row.retired) {
      if (source.deactivated_at === null) {
        await d1Query(
          cfg,
          guard.databaseId,
          `UPDATE knowledge_sources SET deactivated_at = ?, deactivator_name = ${sqlString(brand.name)}, updated_at = ?
            WHERE id = ? AND deactivated_at IS NULL`,
          [now, now, source.id]
        )
        await indexSource(env, cfg, guard, source.id)
        indexed++
      }
      continue
    }
    // ── RETIRED, BY WHOM? The row is live again, and the two answers to that
    // question want opposite things.
    //
    // A source somebody EXCLUDED BY HAND stays excluded. That is what taking the
    // assistant's sight of something means, and no amount of sweeping may give
    // it back.
    //
    // A source THE APP ITSELF retired is a different sentence: it was retired
    // because the row had left — archived, switched off, a Google space no longer
    // shared — and the row is here, so it has not. Until now both were the same
    // `continue`, which made every retirement in this app PERMANENT: un-archive a
    // ticket and its source never returned, because a retired source is never
    // visited again.
    //
    // MEASURED ON STAGING, 26 Aug 2026, in the worst form this takes. Switching
    // off a Google connection switches off the named folders and spaces with it
    // (`disconnect`, google.ts — deliberately, so a share cannot silently come
    // back). At 18:59 on the 25th every named Chat space went off that way; the
    // replacements were written at 04:39:54 the next morning. A housekeeping pass
    // ran at 04:38, in the gap, and retired all 67 Chat conversations the base
    // held — correctly, at that instant, because nothing was shared. Seventy-four
    // seconds later the same eight spaces were shared again, and not one of those
    // conversations could come back. 81% of the team's Chat sat in the list, was
    // counted on screen, looked synced, and could never be quoted again. The
    // retirement was right; only its permanence was wrong.
    //
    // `deactivator_id` is what separates them, structurally rather than by
    // reading a name: `setSourceActive` stamps the actor's id, and both machine
    // retirements leave it null.
    if (source.deactivated_at !== null) {
      if (source.deactivator_id !== null) continue
      await d1Query(
        cfg,
        guard.databaseId,
        // R17: the predicate rides the UPDATE — a source a PERSON excluded in the
        // meantime moves zero rows here, and two ticks racing do this once.
        `UPDATE knowledge_sources SET deactivated_at = NULL, deactivator_name = NULL, updated_at = ?
          WHERE id = ? AND deactivated_at IS NOT NULL AND deactivator_id IS NULL`,
        [now, source.id]
      )
      // REVIVE, THEN REBUILD — the same two steps, in the same order, as the
      // `retired` branch above.
      //
      // FORCED, because everything the hash-skip below would read describes a
      // CLEARED index: retiring a source drops its chunks, and `chunk_count` and
      // `indexed_chunks` both sit at zero, where `0 >= 0` reads as "already fully
      // indexed". Today `clearIndex` also nulls the content hash, so the skip
      // happens not to bite — but that is a second fact in another file, and a
      // row put back on screen with nothing behind it is precisely the state this
      // branch exists to end. It does not depend on which path retired the row.
      await indexSource(env, cfg, guard, source.id, { force: true })
      indexed++
      continue
    }
    // THE SKIP THAT PAYS FOR THE SWEEP: unchanged text is not re-chunked, so it
    // costs no embedding call and no writes. Both halves are needed — a source
    // whose hash matches but whose indexing did not FINISH (a big document, a
    // tick that died) has to be picked up and carried on.
    if (source.content_hash === hash && source.indexed_chunks >= source.chunk_count) continue
    await indexSource(env, cfg, guard, source.id)
    indexed++
  }

  const caughtUp = rows.length < limit
  // A ROLLUP KIND THAT HAS REACHED THE END STARTS AGAIN NEXT TICK. Its text is
  // built from rows its own cursor cannot see (an account's apps, sprints,
  // tickets, people), so "nothing past the cursor" does not mean "nothing has
  // changed" — it means this table has no NEWER rows, while the world described
  // by the rows it already passed moved underneath. Dropping the position here
  // rather than re-reading in the same tick is what keeps `caughtUp` honest: the
  // backfill script loops until every kind says it has finished, and a kind that
  // never says so never lets it stop.
  await recordRun(cfg, guard, stateKey, {
    cursor: last && !(caughtUp && kind.rollup) ? writeCursor(last, kind.textVersion) : null,
    indexed,
    error: null,
  })
  return { kind: stateKey, read: rows.length, indexed, caughtUp }
}

/** Stamp what a tick did on the kind's own row — including, and especially, what
 * went wrong (R12). `last_ok_at` moves only on a clean run, so "it has been
 * running and failing since Tuesday" is readable from the row itself rather than
 * from a log nobody opens. */
async function recordRun(
  cfg: D1Rest,
  guard: MemberGuard,
  kind: string,
  outcome: { cursor: string | null; indexed: number; error: string | null }
): Promise<void> {
  const now = new Date().toISOString()
  await d1ExecScript(
    cfg,
    guard.databaseId,
    `INSERT INTO knowledge_ingest (kind, cursor, last_run_at, last_ok_at, last_error, runs, sources_indexed)
     VALUES (${sqlString(kind)}, ${sqlString(outcome.cursor)}, ${sqlString(now)}, ${outcome.error ? "NULL" : sqlString(now)}, ${sqlString(outcome.error)}, 1, ${outcome.indexed})
     ON CONFLICT (kind) DO UPDATE SET
       cursor = ${outcome.error ? "knowledge_ingest.cursor" : "excluded.cursor"},
       last_run_at = excluded.last_run_at,
       last_ok_at = ${outcome.error ? "knowledge_ingest.last_ok_at" : "excluded.last_ok_at"},
       last_error = excluded.last_error,
       runs = knowledge_ingest.runs + 1,
       sources_indexed = knowledge_ingest.sources_indexed + ${outcome.indexed};`
  )
}

/** One tick over a LIST of kinds. A kind that throws is RECORDED and the rest of
 * the sweep still runs — one bad table must not stop the others from catching
 * up, and a failure that stopped everything silently is the shape R12 exists for.
 *
 * The list is a parameter, and that is the whole of the separation between the
 * sweep the CRON runs and the one a PERSON runs: same engine, same resumability,
 * same failure record, two sets of kinds. See sweepAll below for why the second
 * set cannot be reached from a schedule. */
export async function sweepKinds(
  env: Env,
  cfg: D1Rest,
  guard: MemberGuard,
  kinds: IngestKind[],
  limit = INGEST_SOURCES_PER_TICK
): Promise<SweepResult[]> {
  const results: SweepResult[] = []
  // OLDEST-SWEPT FIRST, so no kind is permanently starved by the one in front.
  //
  // The list was walked in DECLARATION order, which is fine only while a tick
  // can finish it. It cannot any more: since the Drive walk started descending
  // into subfolders it reads several hundred files before filing a row, and a
  // tick that runs out of room stops wherever it got to — always in the same
  // place, because the order never changed.
  //
  // Measured on the owner's staging base, 20 Aug 2026: `document` had run 194
  // times, `email` 186, `event` 183 and `message` 180. The lane declared first
  // had swept fourteen more times than the lane declared last, and the gap grows
  // every tick. `message` was two ticks from being re-indexed with the new chat
  // names and would have kept slipping.
  //
  // Same rotation, and the same reasoning, as the PEOPLE loop in
  // google-autopilot.ts: with more work than a tick can hold, the one waiting
  // longest goes first and everybody comes round. A kind that has never run
  // sorts first of all, which is the right answer for a lane just added.
  const keys = kinds.map((k) => k.stateKey ?? k.kind)
  const lastRun = new Map<string, string>()
  try {
    for (const st of await listIngestState(cfg, guard, keys)) lastRun.set(st.kind, st.lastRunAt ?? "")
  } catch {
    // The order is an optimisation, never a precondition. If the state cannot be
    // read, sweep in declaration order exactly as before.
  }
  const ordered = [...kinds].sort((a, b) =>
    (lastRun.get(a.stateKey ?? a.kind) ?? "").localeCompare(lastRun.get(b.stateKey ?? b.kind) ?? "")
  )
  for (const kind of ordered) {
    const stateKey = kind.stateKey ?? kind.kind
    try {
      results.push(await sweepKind(env, cfg, guard, kind, limit))
    } catch (e) {
      const error = e instanceof Error ? e.message : String(e)
      await recordRun(cfg, guard, stateKey, { cursor: null, indexed: 0, error })
      results.push({ kind: stateKey, read: 0, indexed: 0, caughtUp: false, error })
    }
  }
  // THE SWEEP OWES THE FEED A LINE — but only when it changed something. A row
  // per quiet tick would be 96 lines of noise a day (R17's philosophy: silence
  // when nothing moved); a sweep that filed passages is a real change to what
  // the team knows, made by nobody at a keyboard, which is exactly what a feed
  // is for. Best-effort like every recorder here.
  const indexedNow = results.reduce((n, r) => n + r.indexed, 0)
  if (indexedNow > 0) {
    await logActivity(cfg, guard.databaseId, { id: guard.userId, email: "", name: "Automatic sync" }, {
      type: "Knowledge updated",
      description: `Automatic sync filed ${indexedNow} ${indexedNow === 1 ? "passage" : "passages"} into the knowledge base`,
      relatedTable: "knowledge_sources",
      relatedRowId: guard.teamId,
    }).catch(() => {})
  }
  return results
}

/** ROWS ONE CATCH-UP READS PER KIND. Smaller than a cron tick's slice on
 * purpose: this runs in front of a QUESTION, so it is sized to close the gap
 * between "somebody changed a ticket" and "somebody asked about it", not to
 * backfill a history. When nothing has changed it is two keyed reads per kind
 * and no model call at all. */
const CATCH_UP_PER_KIND = 5

/** BRING THE INDEX UP TO DATE BEFORE ANSWERING — the mechanism behind "no manual
 * sync button, no periodic syncs; everything is quick, everything is silent,
 * everything is instant."
 *
 * WHY A CATCH-UP ON THE READ RATHER THAN A HOOK ON EVERY WRITE. The obvious
 * build is: every door that changes a ticket also re-indexes it. That is an
 * invariant fifty call sites across three workers have to remember, and the one
 * that forgets is silent — the assistant simply answers with last quarter-hour's
 * truth and nobody can tell. This cannot be forgotten: each kind is read in
 * `updated_at` order, so a row that changed sorts after the cursor BY
 * CONSTRUCTION, whoever changed it and through whichever door — an import, the
 * agent, a colleague's browser, a migration.
 *
 * BEST-EFFORT, ALWAYS. A question must still be answerable when the catch-up
 * cannot run; the answer is then as current as the last sweep, which is the
 * failure the 15-minute cron already exists to bound. The failure is recorded on
 * the kind's own row by `sweepKind` (R12), so "it has been failing since
 * Tuesday" is readable rather than invisible. */
export async function catchUp(env: Env, cfg: D1Rest, guard: MemberGuard): Promise<number> {
  const results = await sweepAll(env, cfg, guard, CATCH_UP_PER_KIND)
  return results.reduce((n, r) => n + r.indexed, 0)
}

/**
 * One tick over every kind THIS APP OWNS THE ROWS OF — what the 15-minute cron
 * sweeps, and what a person pressing "bring it up to date" sweeps.
 *
 * IT IS `INGEST_KINDS` AND NOTHING ELSE, and that is a boundary rather than a
 * default. The Google kinds live in a second list (lib/knowledge-google.ts) that
 * this function does not import and cannot name, because everything in it is
 * read with ONE PERSON'S OWN TOKEN: a sweep of somebody's mailbox has to run as
 * that person or not at all. The cron has no caller and builds a guard whose
 * user id no row can hold — so if the two lists were one, that guard would
 * resolve no connection and the sweep would quietly do nothing, which is the
 * right failure but an invisible one. Two lists make it a fact of the code
 * instead: there is no argument the scheduled handler could pass that would
 * reach a personal kind.
 */
export async function sweepAll(
  env: Env,
  cfg: D1Rest,
  guard: MemberGuard,
  limit = INGEST_SOURCES_PER_TICK
): Promise<SweepResult[]> {
  return sweepKinds(env, cfg, guard, INGEST_KINDS, limit)
}

/** What the sweep has done so far, per kind — the screen's "is it in step?" row
 * and the machine surface's answer to the same question. */
export type IngestState = {
  kind: string
  cursor: string | null
  lastRunAt: string | null
  lastOkAt: string | null
  lastError: string | null
  runs: number
  sourcesIndexed: number
}

export async function listIngestState(
  cfg: D1Rest,
  guard: MemberGuard,
  /** the caller's own personal state keys (their Google kinds), so the screen
   * shows how far THEIR material has got and never a colleague's. Empty when the
   * caller has no Google right — the sync screen then reads exactly as it did
   * before this lane existed. */
  personalKeys: string[] = []
): Promise<IngestState[]> {
  // NAMED, NOT SCANNED. The table now holds a row per person per Google kind, so
  // "everything in it" would be one member's screen showing every colleague's
  // sweep. The keys are code-known — the shared kinds plus the caller's own — so
  // the read asks for exactly the rows it may show, and R14's cap is the length
  // of a list this statement is carrying anyway.
  const keys = [...INGEST_KINDS.map((k) => k.stateKey ?? k.kind), ...personalKeys]
  const rows = await d1Query<{
    kind: string
    cursor: string | null
    last_run_at: string | null
    last_ok_at: string | null
    last_error: string | null
    runs: number
    sources_indexed: number
  }>(
    cfg,
    guard.databaseId,
    // R14 hard cap: one row per named key, and the names are a fixed list in code.
    `SELECT kind, cursor, last_run_at, last_ok_at, last_error, runs, sources_indexed
       FROM knowledge_ingest WHERE kind IN (${keys.map(() => "?").join(", ")})
      ORDER BY kind LIMIT ${keys.length}`,
    keys
  )
  return rows.map((r) => ({
    kind: r.kind,
    cursor: r.cursor,
    lastRunAt: r.last_run_at,
    lastOkAt: r.last_ok_at,
    lastError: r.last_error,
    runs: r.runs,
    sourcesIndexed: r.sources_indexed,
  }))
}
