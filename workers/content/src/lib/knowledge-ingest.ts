/** Rows one kind may ingest per tick. The bound on the work a single invocation
 * does — the reason a cron handler here cannot become a long-running job. Sized
 * so the whole sweep (every kind) fits comfortably inside one invocation even
 * when every row has changed and every chunk needs embedding. */
export const INGEST_SOURCES_PER_TICK = 25

/** Replies folded into a ticket's text. A ticket's conversation is most of what
 * makes it useful to the assistant, and THREAD_HARD_CAP is the same ceiling the
 * ticket screen reads it under (R14) — the index must not be able to ask for
 * more of a row than a person can. */
const REPLIES_PER_TICKET = Math.min(50, THREAD_HARD_CAP)

/** A row on its way to becoming a source. `sortAt` is the cursor's value. */
export type IngestRow = {
  originRowId: string
  sortAt: string
  title: string
  /** WHAT THIS RECORD IS ABOUT, in a sentence or two, derived from the row's own
   * columns (knowledge-summary.ts). The router searches these before it searches
   * any material, and a list screen shows them instead of dragging bodies over
   * the wire. Never generated by a model — see that file for the four reasons. */
  /** OPTIONAL, and only because Google's kinds have none yet: a document out of
   * somebody's Drive arrives as itself, with no record around it to summarise.
   * Every kind this app owns the rows of builds one, and the router falls back
   * to the title where there is none. */
  summary?: string
  body: string
  accountId: string | null
  /** the rest of the notebook: which built system, which ticket, which sprint. */
  appId?: string | null
  ticketId?: string | null
  sprintId?: string | null
  /** when the material is FROM. Falls back to the row's own timestamps. */
  recordDate?: string | null
  sourceUrl: string | null
  /** TRUE when the row has left the part of the app this kind mirrors — archived,
   * switched off, deleted. The source is DEACTIVATED rather than skipped, which
   * is the difference between "the assistant stops quoting it" and "the
   * assistant quotes it forever because the sweep never visits it again". */
  retired?: boolean
  /** WHO THIS MAY EVER ANSWER FOR. Null = the team's, which is what every row
   * this app owns is: a ticket, an app and an account belong to everybody
   * who may read the module. A person's id means the material arrived through
   * ONE PERSON'S OWN SIGHT of it (their Drive, their mailbox) and is readable
   * only in THEIR answers — the personal fence lib/knowledge.ts applies to every
   * read, including the search.
   *
   * It is on the ROW rather than on the kind because a single Google kind
   * carries both: a folder somebody filed as team material and one they kept to
   * themselves come back from the same read, and the shelf is on each item. */
  ownerUserId: string | null
}

/** One kind of in-app material: where it lives, and how a row of it reads.
 *
 * `read` takes the cursor's position and hands back the next slice in cursor
 * order. It is SQL rather than a call to each module's own list function on
 * purpose: a list function answers what a SCREEN needs (fenced, shaped, capped
 * at a page), and this needs whole rows in a stable total order — asking a
 * screen's reader for that would bend it out of shape for a job it is not for. */
export type IngestKind = {
  kind: string
  /** WHERE THIS KIND KEEPS ITS PLACE, when that is not simply its name.
   *
   * The three kinds below sweep a TABLE, and a table has one position however
   * many people are looking at it. A Google kind sweeps ONE PERSON'S sight of an
   * external system, so Ana's Drive and Ben's Drive are two sweeps with two
   * positions and two error records — the same kind, twice. Defaulting to `kind`
   * is what keeps that invisible to everything that does not need to know. */
  stateKey?: string
  /** which table a source of this kind mirrors — also its `origin_table` */
  table: string
  /** plain words for the activity trail and the failure message */
  label: string
  read: (
    cfg: D1Rest,
    guard: MemberGuard,
    after: Cursor | null,
    limit: number,
    /** THE GLOBAL CORE DATABASE, for the one kind whose material is not in the
     * team's own. Every other kind mirrors a team table and never looks at it.
     *
     * Membership is GLOBAL — `team_members` and `users` live in core (see
     * lib/members.ts's own header) — and `staff_profiles` in the team database
     * carries a `user_id` and NO NAME AT ALL. So "who is Alex?" was a question
     * no team table could answer, which is why it is the one kind that takes
     * this. Passed rather than closed over so `INGEST_KINDS` stays a plain
     * array every test and script can read without building an environment;
     * the Google kinds close over theirs instead, for the different reason
     * their own file gives. */
    env: Env
  ) => Promise<IngestRow[]>
  /** MIRRORS A WINDOW, NOT A TABLE. The three kinds above walk a table that has
   * a first row and a last one, so a cursor that reaches the end has finished.
   * A Google kind reads what one API call HANDS BACK — the fifty most recently
   * changed files in a folder, the newest messages in a space — and that window
   * slides: a document edited today enters it, one nobody has touched since 2023
   * leaves it. A cursor over a sliding window would stop at the newest thing it
   * ever saw and never look behind itself again, so a windowed kind REWINDS the
   * moment it catches up and walks the window again — in the same tick, so that
   * a change with no new timestamp on it (a folder re-shelved) lands on the very
   * next press rather than the one after. See sweepKind.
   *
   * That is only affordable because of the hash: a re-walk over unchanged
   * material is one cheap upsert per item, no chunking, no embedding call. It is
   * the same trade the sweep already makes everywhere else, said once more for a
   * source whose order we do not control. */
  windowed?: boolean
  /** ITS TEXT DEPENDS ON ROWS THE CURSOR CANNOT SEE.
   *
   * An account's source is a ROLLUP — its apps, its sprints, its open tickets,
   * its people. None of those moves `accounts.updated_at`, so a cursor on that
   * column would file the account once and never look at it again while its
   * whole world changed underneath. A rollup kind therefore DROPS ITS CURSOR the
   * moment it catches up, so the next tick starts the table again and every
   * account's text is rebuilt on a rolling cycle.
   *
   * It is not `windowed`, and the difference matters: a windowed kind re-walks
   * in the SAME tick and so never reports `caughtUp`, which is the signal the
   * backfill script loops on. A rollup kind reports the truth — it has reached
   * the end of the table — and simply starts again next time. So the backfill
   * still terminates.
   *
   * Cheap by construction, twice over: the sort is the account's own timestamp
   * (the rollup sub-selects are evaluated only for the rows the slice RETURNS,
   * never for the whole table), and anything whose text really did not change is
   * hash-skipped before a single chunk is written. */
  rollup?: boolean
  /** ITS ROWS ARE NOT IN THE TEAM'S DATABASE.
   *
   * True of exactly one kind, `person`, and it is a fact about the base rather
   * than a flag for a test: MEMBERSHIP IS GLOBAL. `team_members` and `users`
   * live in the core database (lib/members.ts's own header says so), while
   * `staff_profiles` — the team's half of the same person — carries a `user_id`
   * and no name at all. So this kind reaches `env.DB` for the names and the
   * team database for the profile, and it is the only one that does.
   *
   * It is declared because everything that reasons about the sweep otherwise
   * assumes `table` names a team table it can count: the backfill suite's
   * expected-source count would read the TEAM's own `users` rows, which in
   * production is a table that does not exist and in a single-database fixture
   * is a different set of people. Rot-checked — a kind claiming this must
   * really name `env.DB` in its own reader, and one that names `env.DB` must
   * claim it. */
  fromCoreDatabase?: boolean
  /** WHAT ONE SOURCE OF THIS KIND IS, when it is not one row of `table`.
   *
   * Almost every kind mirrors a row: one ticket, one source. `dropdown` mirrors
   * a LIST — "what ticket types do we use" is answered by the list and not by
   * any one of its rows — so its sources are the DISTINCT values of one column
   * (`type`), and its `originRowId` is that value.
   *
   * It is declared rather than inferred because something has to be able to
   * check the invariant this file's whole design rests on: one source per thing
   * mirrored, no duplicates, safe to re-run. The backfill suite derives its
   * expected count from the kinds themselves rather than from a list written in
   * the test, and a kind that quietly stopped being one-per-row would otherwise
   * turn that derivation into a number nobody could explain. */
  oneSourcePer?: string
  /** THE PERMISSION MODULES THIS KIND'S TEXT PUTS IN THE CORPUS (R47), when its
   * own `table` is not the whole answer. Default: the module `table` maps to.
   *
   * Only `person` needs it today, and it needs it because it is a JOIN across
   * the fence between the two databases: the row is `users` (the `team_members`
   * module) and the text also carries the staff profile and certificates
   * (`staff_profiles`). One source, two modules — and a census that read the
   * table alone would report the second as missing from the corpus while its
   * words were sitting in it.
   *
   * Rot-checked by the coverage suite: every module named here must be a real
   * TEAM_MODULE, and the kind's own read must really mention the table behind
   * it, so this can never become a way to CLAIM coverage a reader does not have. */
  modules?: string[]
  /** WHICH TEXT BUILDER WROTE THE ROWS ALREADY IN THE INDEX.
   *
   * The hash answers "has this ROW changed?", which is a different question from
   * "has the way we WRITE this row changed?" — and the cursor makes the second
   * one fatal. A ticket indexed in March is behind the cursor forever unless
   * somebody touches it, so improving the ticket text reaches every future
   * ticket and not one existing one. That is a change that looks shipped and is
   * not, which is the shape of failure this codebase keeps legislating against.
   *
   * So the version rides IN the cursor (`v<n>|<sort>|<id>`). A stored cursor
   * whose version is not this one is not a position at all — it is a page number
   * in a book that has been rewritten — so it reads as null and the kind walks
   * its table again from the start, re-hashing as it goes. One rewind, then the
   * ordinary steady state.
   *
   * CHANGE THE TEXT A KIND PRODUCES → BUMP ITS VERSION. Not a convention:
   * `workers/content/test/knowledge-coverage.test.ts` pins a hash of each kind's
   * own source to the number declared here, so a builder edited without a bump
   * turns the build red and says so. */
  textVersion: number
}

type Cursor = { at: string; id: string }

/** The keyset predicate every kind's read shares: everything strictly after the
 * cursor, in (sort value, id) order. Forward, not backward like a screen's page:
 * a sweep is catching UP, so it reads oldest-first and stops when it runs out.
 *
 * `idExpr` is QUALIFIED by every caller that joins. It used to be a bare `id`,
 * which was fine while each read was one table and became "ambiguous column
 * name: id" the moment a reader joined `accounts` to get the client's name —
 * and the sweep swallows a kind's error and carries on (R12), so the failure
 * showed up as a ticket that simply never stopped answering. */
function after(cursor: Cursor | null, sortExpr: string, idExpr = "id"): { sql: string; params: string[] } {
  if (!cursor) return { sql: "", params: [] }
  return {
    sql: `(${sortExpr} > ? OR (${sortExpr} = ? AND ${idExpr} > ?))`,
    params: [cursor.at, cursor.at, cursor.id],
  }
}

const TICKET_SORT = "COALESCE(h.updated_at, h.created_at)"

/** Children of one record folded into its own text — apps under an account,
 * steps under a process, stories under a sprint. Bounded so that a rollup is a
 * paragraph rather than a book: an account with four hundred tickets must not
 * produce a source nobody can chunk usefully, and one enormous chunk would crowd
 * every other passage out of an answer. */
const ROLLUP_ROWS = 20
/** People, which are fewer and matter more — who we deal with at a client is
 * usually the whole question. */
const ROLLUP_CONTACTS = 15
/** The steps of a process map's LATEST version. Higher than the rest because the
 * steps ARE the map: an eleven-step invoice run cut at five is not a summary of
 * the process, it is a wrong answer about it. */
const PROCESS_STEPS = 40
/** What has been said on a process map — the client's own words about how they
 * work, which is material nothing else in this app holds. */
const PROCESS_COMMENTS = 20
/** Notes on the time logged against one record. A work log's note is often the
 * only written account of what was actually done in a sitting. */
const WORK_NOTES = 20

/** ONE BOUNDED CHILD LIST, as a correlated `group_concat` over an inner select
 * that carries its own LIMIT — the exact shape a ticket's conversation has ridden
 * on since the sweep was built, said once so every kind below inherits it.
 *
 * ONE ROUND TRIP PER TICK, NOT ONE PER ROW: the alternative (a query per record
 * per child table) turns a 25-row slice into two hundred calls over the REST
 * door, which is how a bounded sweep becomes a long-running job.
 *
 * R14 lives at the call site: `inner` must carry a LIMIT that is a constant in
 * this file, never anything off a request. */
function childLines(inner: string): string {
  return `(SELECT group_concat(x.line, char(10)) FROM (${inner}) x)`
}

/** THE WORDS ON THE TIME LOGGED AGAINST A RECORD, folded into that record.
 *
 * A work log is not a source of its own, and that is a decision rather than an
 * omission. Its note is real material — but thousands of one-line rows ("carried
 * on with the dispatch fix") would compete with tickets, maps and transcripts for
 * the six passages an answer carries, and a search that has to choose between a
 * process map and a timer entry will sometimes choose wrong. Folded in here, the
 * words are searchable and they arrive attached to the work they were written
 * about. Discarded logs are left out: somebody binned them.
 *
 * `target` is a SQL literal this file writes (`'help'`), never a value off a
 * request. */
function workNotes(target: string, idExpr: string): string {
  return `SELECT w.note AS line FROM work_logs w
           WHERE w.target_table = ${target} AND w.target_id = ${idExpr}
             AND w.discarded_at IS NULL AND w.note IS NOT NULL AND w.note <> ''
           ORDER BY w.started_at LIMIT ${WORK_NOTES}`
}

